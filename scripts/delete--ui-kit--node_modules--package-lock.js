/* eslint-disable no-console */
import fs from 'fs';
import path from 'path';

const { dirname } = import.meta;

const PATHS_FOR_DELETE = {
  UIkitNodeModules: ['../', 'packages', 'ui-kit', 'node_modules'],
  UIkitPackageLock: ['../', 'packages', 'ui-kit', 'package-lock.json'],
};

const targetPaths = Object.values(PATHS_FOR_DELETE).map((p) =>
  path.resolve(dirname, ...p)
);

targetPaths.forEach((targetPath) => {
  fs.rm(targetPath, { recursive: true, force: true }, (err) => {
    if (err) {
      console.error(`Ошибка при удалении ${targetPath}: `, err.message);
      process.exit(1);
    } else {
      console.log(`Удалено: ${targetPath}`);
    }
  });
});
