/**
 * Проверяет, является ли ячейка пустой в grid-template-areas
 *
 * Пустыми считаются ячейки, которые не содержат имени области или содержат
 * специальные символы, используемые для обозначения пустых областей в CSS Grid.
 *
 * @param cell - строка, представляющая содержимое ячейки
 * @returns true если ячейка пустая, false если содержит имя области
 *
 * @example
 * isEmptyCell('.')    // true - точка означает пустую область
 * isEmptyCell('-')    // true - тире означает пустую область
 * isEmptyCell(' ')    // true - пробел означает пустую область
 * isEmptyCell('')     // true - пустая строка
 * isEmptyCell('header') // false - содержит имя области
 */
export const isEmptyCell = (cell: string) =>
  !cell || cell === '.' || cell === '-' || cell === ' ';
