/**
 * Выравнивание текста в слитой ячейке шапки (по горизонтали и вертикали).
 */
export type HeaderAlignment = {
  /** По горизонтали. @default 'left' */
  horizontal?: 'left' | 'center' | 'right';
  /** По вертикали. @default 'center' */
  vertical?: 'top' | 'center' | 'bottom';
};

/**
 * Конфиг группировки колонок (многоуровневая шапка через `columnConfig.children`).
 * Управляет объединением ячеек шапки на уровне всей таблицы.
 */
export type ColumnsGroupingConfig = {
  /**
   * Схлопнуть пустые ячейки шапки: листовая колонка без группы тянется вверх, «мелкая»
   * группа (без более глубоких подгрупп) — вниз. Убирает пустые полосы в многоуровневой
   * шапке. Включает/выключает поведение сразу для всей таблицы.
   * @default true
   */
  squashEmptyCells?: boolean;
  /**
   * Дефолт выравнивания текста в слитых ячейках шапки. Точечно перекрывается на колонке
   * или группе через их собственный `squashedHeaderAlign`.
   */
  squashedHeaderAlign?: HeaderAlignment;
};
