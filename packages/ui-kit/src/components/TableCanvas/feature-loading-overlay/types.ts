import { ReactNode } from 'react';

export type LoadingOverlayMode = 'replace' | 'cover';

export type LoadingOverlayConfig = {
  /**
   * Активен ли оверлей загрузки
   * @default true
   */
  active?: boolean;
  /**
   * Как оверлей показывается относительно таблицы.
   * - 'replace' — оверлей занимает место таблицы, таблица при этом размонтируется:
   *   после снятия оверлея выделение, страница пагинации и прокрутка начинаются заново.
   *   Подходит для первой загрузки, когда таблицы ещё нет.
   * - 'cover' — таблица остаётся на месте, оверлей ложится поверх неё целиком
   *   (control block, боковые панели, нижняя панель, пагинация, в том числе в fullscreen)
   *   полупрозрачным размытым слоем и блокирует мышь, клавиатуру и фокус.
   *   Состояние таблицы сохраняется. Подходит для долгих действий с уже открытой таблицей.
   * @default 'replace'
   */
  mode?: LoadingOverlayMode;
  /**
   * Кастомный компонент спиннера
   * @default <Spinner view="secondary" size="l" />
   */
  spinner?: ReactNode;
  /**
   * Основной заголовок оверлея
   * @default 'Загрузка таблицы' для mode: 'replace', 'Таблица обновляется' для mode: 'cover'
   */
  title?: string;
  /**
   * Подзаголовок, который появится после задержки, пустая строка - значит он не появится
   * @default ""
   */
  subtitle?: string;
  /**
   * Задержка перед показом подзаголовка (мс)
   * @default 10000 (10 секунд)
   */
  showSubtitleDelay?: number;
};
