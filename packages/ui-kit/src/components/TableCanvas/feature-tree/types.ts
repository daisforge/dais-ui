export type SubRows<RowType, RowIdType> = {
  /**
   * Возвращает дочерние строки узла (или undefined, если их нет).
   *
   * Функция должна быть стабильной — не менять поведение между рендерами.
   * Если она зависит от чего-то меняющегося, оберните её в useCallback.
   */
  getSubRows: (row: RowType) => RowType[] | undefined;
  /**
   * Возвращает уникальный ключ строки.
   *
   * Функция должна быть стабильной — не менять поведение между рендерами.
   * Если она зависит от чего-то меняющегося, оберните её в useCallback.
   */
  rowKeyGetter: (row: RowType) => RowIdType;
  /**
   * Внешний стейт развёрнутых строк.
   * Если не задан — используется внутренний useState.
   */
  expandedIdsState?: [
    Set<string | number>,
    (
      newV:
        | Set<string | number>
        | ((prev: Set<string | number>) => Set<string | number>),
    ) => void,
  ];
  /**
   * Как показывать дерево.
   * 'tree' (по умолчанию) — узлы с раскрытием (шевроны) и отступом по уровню.
   * 'merged' — дерево разворачивается в листья, а колонки-предки показаны
   * объединёнными ячейками. Структуру задаёт потребитель через getSubRows;
   * данные (пагинация, сортировка, поиск) остаются на его стороне.
   */
  view?: 'tree' | 'merged';
  /**
   * Только для view: 'merged'. Колонки-предки по порядку уровней:
   * mergedColumns[0] — верхний уровень, дальше глубже. Каждая такая колонка
   * показывает значение своего узла-предка (узел должен нести поле с этим именем)
   * и объединяется по его границам. Верхний уровень задаёт чекбокс и номер блока.
   */
  mergedColumns?: string[];
};
