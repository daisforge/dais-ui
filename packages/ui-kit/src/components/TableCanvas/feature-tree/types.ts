export type SubRows<RowType, RowIdType> = {
  /**
   * Функция получения дочерних строк.
   *
   * ⚠️ **Должна быть чистой и стабильной** — не менять логику между рендерами.
   *
   * Если структура дерева может динамически меняться — оберните в `useCallback`.
   */
  getSubRows: (row: RowType) => RowType[] | undefined;
  /**
   * Функция получения уникального ключа строки.
   *
   * ⚠️ **Должна быть чистой и стабильной** — не менять логику между рендерами.
   *
   * Если логика получения ключа может динамически меняться — оберните в `useCallback`.
   */
  rowKeyGetter: (row: RowType) => RowIdType;
  /**
   * Внешний стейт развёрнутых строк.
   * Если не задан — используется внутренний `useState`.
   */
  expandedIdsState?: [
    Set<string | number>,
    (
      newV:
        | Set<string | number>
        | ((prev: Set<string | number>) => Set<string | number>),
    ) => void,
  ];
  /**
   * Вид отображения дерева.
   * - `'tree'` (по умолчанию) — узлы-строки с шевронами и отступом.
   * - `'merged'` — дерево разворачивается в листья, а колонки-предки рисуются
   *   СЛИТЫМИ ячейками (как `rowsGrouping.view: 'merged'`), но структуру задаёт
   *   потребитель через `getSubRows`. Даёт нативные «один чекбокс / один индекс
   *   на блок» и сохраняет владение данными (пагинация/сортировка/поиск снаружи).
   */
  view?: 'tree' | 'merged';
  /**
   * Только для `view: 'merged'`. Упорядоченный список колонок-предков: индекс =
   * уровень дерева. `mergedColumns[d]` сливается по границам своего предка уровня
   * `d`; значение объединённой ячейки берётся из поля узла-предка по этому ключу
   * (узлы-предки должны нести поле с этим именем). Верхний уровень
   * (`mergedColumns[0]`) — единица чекбокса и нумерации блока.
   */
  mergedColumns?: string[];
};
