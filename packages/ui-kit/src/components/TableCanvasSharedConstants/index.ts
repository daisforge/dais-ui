export const DURATION = 0.5;

/**
 * Анимация сворачивания таблицы.
 * Тело таблицы едет по высоте за COLLAPSE_DURATION. Декор кромки блоков
 * (скругление нижних углов + цвет нижнего бордера) переключается НЕ сразу
 * по isCollapsed, а с задержкой COLLAPSE_DECOR_DELAY — то есть уже ПОСЛЕ
 * того как тело схлопнулось. Иначе декор «едет» рано, пока контент ещё
 * виден: углы скругляются преждевременно, а нижний бордер на стыке блоков
 * на момент анимации даёт двойную линию. При разворачивании задержки нет
 * (декор сбрасывается мгновенно). COLLAPSE_DECOR_FADE — мягкое проявление
 * цвета нижнего бордера, чтобы он не возникал резко.
 */
export const COLLAPSE_DURATION = DURATION;
export const COLLAPSE_DECOR_DELAY = DURATION;
export const COLLAPSE_DECOR_FADE = 0.15;

/**
 * Id узла канваса для тултипа индикатора скрытых столбцов (полосатая линия на
 * границе в шапке). Кросс-слойный контракт: событие ховера шлёт TableGlide, а текст
 * по этому id резолвит feature-tooltip в TableCanvas. Поэтому id лежит в нейтральном
 * общем слое, чтобы оба брали его отсюда, а не друг у друга.
 */
export const HEADER_TOOLTIP_HIDDEN_COLS_ID = 'header-tooltip-hidden-cols';
