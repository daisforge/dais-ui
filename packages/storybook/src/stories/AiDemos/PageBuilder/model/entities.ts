/** Правдоподобные мок-значения по названию колонки или поля */
export function mockValue(column: string, index: number): string | number {
  const name = column.toLowerCase();
  const pick = (list: string[]) => list[index % list.length] ?? '';
  if (/статус/.test(name))
    return pick([
      'Исполнен',
      'На согласовании',
      'Черновик',
      'Отклонён',
      'В работе',
    ]);
  if (/сумма|ндс/.test(name))
    return Math.round(((index * 7919) % 900000) + 15000);
  if (/дата|срок|до$|приём/.test(name))
    return `${String(((index * 3) % 28) + 1).padStart(2, '0')}.${String(
      (index % 12) + 1,
    ).padStart(2, '0')}.2025`;
  if (/номер|№/.test(name))
    return `${2025}-${String(140 + index).padStart(4, '0')}`;
  if (/контрагент|покупатель|наименован/.test(name))
    return pick([
      'ООО «Альфа-Трейд»',
      'АО «Северсталь-Инвест»',
      'ИП Смирнов А. В.',
      'ООО «ТехноПарк»',
      'ПАО «Энергосбыт»',
    ]);
  if (/инн/.test(name)) return String(7700000000 + index * 13579);
  if (/кпп/.test(name)) return String(770100000 + index * 11);
  if (/фио|ответственн|инициатор|куратор|руковод|автор/.test(name))
    return pick([
      'Иванова М. П.',
      'Петров С. А.',
      'Сидоров К. Н.',
      'Орлова Е. В.',
    ]);
  if (/подразделен/.test(name))
    return pick(['Казначейство', 'Бухгалтерия', 'Закупки', 'ИТ']);
  if (/регион/.test(name))
    return pick(['Москва', 'Санкт-Петербург', 'Новосибирск', 'Казань']);
  if (/риск/.test(name)) return pick(['Низкий', 'Средний', 'Высокий']);
  if (/тип/.test(name))
    return pick(['Оплата поставщику', 'Командировка', 'Закупка', 'Возврат']);
  if (/должност/.test(name))
    return pick(['Аналитик', 'Ведущий экономист', 'Руководитель группы']);
  return pick(['Значение А', 'Значение Б', 'Значение В']);
}
